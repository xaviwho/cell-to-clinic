"""Writes the Cell-to-Clinic II pieces of the paper from committed results/ (no hand-typed numbers):
  paper/generated/c2c2_numbers.tex     \\newcommand macros for every number quoted in the text
  paper/tables/tab_c2c2_deviations.tex deviations from osf.io/4pzxa and post-hoc additions
  paper/sections/c2c2_geqtl_methods.tex methods paragraph for gate G-eQTL
Inputs: results/c2c2_models_da.json, c2c2_g_eqtl.json, c2c2_jerber_leads.json, c2c2_eqtl_attrition.json,
c2c2_explore_batch.json.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES, PAPER = ROOT / "results", ROOT / "paper"
HEADER = "% AUTO-GENERATED by scripts/paper_c2c2.py from results/c2c2_*.json -- do not edit by hand.\n"


def load(n):
    return json.load(open(RES / f"c2c2_{n}.json"))


def f2(x):
    return f"{x:.2f}".replace("-", "$-$")


def fp(p):
    return f"{p:.3f}" if p < 0.1 else f"{p:.2f}"


def numbers(m, g, L, a, b):
    P, S = m["H1_DA_primary"], m["sensitivity"]
    mac = {
        "cctwoN": m["sample"]["n_after_G_cells"], "cctwoAzeroOne": m["A0_1"]["n_meeting_rule"],
        "cctwoBeta": f2(P["estimate"]), "cctwoSE": f2(P["se"]), "cctwoP": fp(P["p"]), "cctwoR": f2(P["r"]),
        "cctwoRlo": f2(P["ci90"][0]), "cctwoRhi": f2(P["ci90"][1]), "cctwoVisits": P["n_obs"],
        "cctwoBatchBeta": f2(S["S4_batch"]["H1_DA_primary"]["estimate"]), "cctwoBatchP": fp(S["S4_batch"]["H1_DA_primary"]["p"]),
        "cctwoOldBeta": f2(S["S1_old_label"]["H1_DA_primary"]["estimate"]), "cctwoOldP": fp(S["S1_old_label"]["H1_DA_primary"]["p"]),
        "cctwoAdjBeta": f2(S["S2_composition_adjusted"]["H1_DA_primary"]["estimate"]), "cctwoAdjP": fp(S["S2_composition_adjusted"]["H1_DA_primary"]["p"]),
        "cctwoIdioP": fp(S["S3_idiopathic"]["H1_DA_primary"]["p"]), "cctwoIdioN": S["S3_idiopathic"]["H1_DA_primary"]["n_donors"],
        "cctwoFiveP": fp(S["S6_first_5y"]["H1_DA_primary"]["p"]),
        "cctwoLooMin": f2(S["S5_leave_one_out"]["loo_min"]), "cctwoLooMax": f2(S["S5_leave_one_out"]["loo_max"]),
        "cctwoAfiveShare": f"{100 * m['A0_5_D4']['share_same_sign']:.0f}", "cctwoAfiveGenes": m["A0_5_D4"]["n_genes"],
        "cctwoHfourP": fp(m["H4_bulk_oxphos"]["p"]), "cctwoSecN": m["secondary_n_in_BH"],
        "cctwoLeads": L["n_lead_bh_fdr05"], "cctwoLeadsQ": f"{L['n_q_lt_05']:,}".replace(",", "{,}"),
        "cctwoTested": g["new"]["n_tested"], "cctwoConc": f2(g["new"]["sign_concordance"]), "cctwoPione": f2(g["new"]["pi1"]),
        "cctwoNullConc": f2(g["new"]["null95_concordance"]), "cctwoNullPione": f2(g["new"]["null95_pi1"]),
        "cctwoExpressed": a["gene_expressed_cpm10"], "cctwoOnArray": a["snp_on_array_any_gene"],
        "cctwoArraySNPs": f"{a['array_snps_total']:,}".replace(",", "{,}"),
        "cctwoBatchRtwoDtwo": f2(b["a_D2_by_batch"]["R2"]), "cctwoBatchPDtwo": fp(b["a_D2_by_batch"]["p"]),
        "cctwoBatchRtwoSlope": f2(b["b_slope_by_batch"]["R2"]), "cctwoBatchPSlope": fp(b["b_slope_by_batch"]["p"]),
        "cctwoRall": f2(b["c_association"]["overall_r"]), "cctwoRwithin": f2(b["c_association"]["within_batch_r"]),
        "cctwoRbetween": f2(b["c_association"]["between_batch_r_n5"]),
    }
    return HEADER + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in mac.items())


def deviations(g, L):
    rows = [
        ("G-eQTL lead source",
         "Leads taken per gene from Jerber's all-SNP summary file (min-$p$ SNP, gene-level empirical $p$, BH).",
         f"Leads from Jerber et al.\\ Suppl.\\ Table~7 (context DA\\_D52; same rule, BH FDR $<$ 5\\%; {L['n_lead_bh_fdr05']} leads).",
         "The released all-SNP files carry no gene-level $p$ (value $-1$ on every row). Decided before any FOUNDIN data was used; "
         f"all {L['n_lead_bh_fdr05']} pairs found in the all-SNP file with identical $\\beta$."),
        ("G-eQTL code version", "Tagged before the run.",
         "\\texttt{g-eqtl-v1.0.0} failed on the real file (no leads); \\texttt{g-eqtl-v1.1.0} used.",
         "Failed version reported, not hidden."),
        ("Implementation readings", "Not specified in the registered text.",
         "H4 composition adjustment as for P3 in registration~1; A0-3 kept with G-cells; registration-1 SAA rule; "
         "sensitivity scope; D1/D3 descriptive.",
         "Fixed in \\texttt{models-da-v1.0.0} before linkage; accepted by the first author without independent review."),
        ("Post-hoc additions", "--",
         "Batch check (\\texttt{explore-II-v0.1.0}); eQTL attrition counts.",
         "Labelled exploratory; specified and tagged before running."),
    ]
    out = [HEADER, "\\begin{table*}[!t]\n\\centering\n\\caption{Deviations from the Cell-to-Clinic~II registration (osf.io/4pzxa) and post-hoc additions.}\n",
           "\\label{tab:c2c2_deviations}\n\\footnotesize\n\\begin{tabular}{p{2.6cm}p{4.2cm}p{4.6cm}p{5.4cm}}\n\\toprule\n",
           "Item & Registered & Done & Reason / note \\\\\n\\midrule\n"]
    out += [" & ".join(r) + " \\\\\n" for r in rows]
    out.append("\\bottomrule\n\\end{tabular}\n\\end{table*}\n")
    return "".join(out)


METHODS = HEADER + r"""\paragraph{Genetic positive control (gate G-eQTL)}
Before any clinical linkage, we asked whether the new DA-neuron pseudobulks carry known DA-neuron genetic
regulation. Lead eQTLs were taken from day-52 untreated DA neurons of Jerber et al.\ (Supplementary Table~7;
one lead SNP per gene, gene-level empirical $p$ from 1{,}000 genotype permutations, BH FDR $<$ 5\%;
\cctwoLeads{} genes; \cctwoLeadsQ{} at Storey $q < 0.05$). Each lead was tested in the FOUNDIN DA pseudobulk
of the 79 donor lines by OLS of $\log_2$(CPM$+1$) on allele dosage with three genotype and five expression
principal components, after matching SNPs on GRCh37 position and alleles and dropping strand-ambiguous
SNPs. The gate passed if sign concordance with Jerber's $\beta$ was at least 0.70 and Storey's $\pi_1$
($\lambda = 0.5$) at least 0.30, both above the 95th percentile of 200 null sets pairing the same genes with
random SNPs on other chromosomes in the same MAF bin. Of the \cctwoLeads{} leads, \cctwoExpressed{} genes were
expressed (CPM $\ge$ 10) and only \cctwoOnArray{} lead SNPs were directly genotyped on the array
(\cctwoArraySNPs{} SNPs; no imputation or proxies were registered), leaving \cctwoTested{} testable pairs.
Concordance was \cctwoConc{} and $\pi_1$ \cctwoPione{} (null 95th percentiles \cctwoNullConc{} and
\cctwoNullPione{}); the gate passed, as it did for the old-label and all-cell pseudobulks. The gate therefore
shows that genetic regulation is present in the new label, not that the new label is more DA-specific.
"""


def main():
    m, g, L, a, b = (load(n) for n in ("models_da", "g_eqtl", "jerber_leads", "eqtl_attrition", "explore_batch"))
    (PAPER / "sections").mkdir(exist_ok=True)
    (PAPER / "generated" / "c2c2_numbers.tex").write_text(numbers(m, g, L, a, b), encoding="utf-8")
    (PAPER / "tables" / "tab_c2c2_deviations.tex").write_text(deviations(g, L), encoding="utf-8")
    (PAPER / "sections" / "c2c2_geqtl_methods.tex").write_text(METHODS, encoding="utf-8")
    print("written: generated/c2c2_numbers.tex, tables/tab_c2c2_deviations.tex, sections/c2c2_geqtl_methods.tex")


if __name__ == "__main__":
    main()
