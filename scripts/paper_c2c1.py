"""Registration-1 (osf.io/s6w9c) and registration-II pre-link aggregates for the J-BHI paper.

Step 1, `export` (run on the analysis machine): copies AGGREGATES ONLY from the git-ignored
data/derived/ JSONs into committed results/:
  results/c2c1_registration1.json  pipeline reproduction, A0-4, A0-2, A0-3, A0-1, A0-5, the 10 tests
                                   (estimate, SE, df, p, q, partial r, 90% CI, n, class) and
                                   per-variant class counts of the registered sensitivity analyses
  results/c2c2_prelink.json        DA-label calibration and marker enrichment (B0), G-cells, G-icc
No IDs, no per-line values: every field is a count, a summary statistic or a model estimate.

Step 2, default (no argument): writes the paper pieces from results/ only:
  paper/generated/c2c1_numbers.tex   \\newcommand macros (prefix \\ccone)
  paper/tables/tab_gates.tex         every gate of both registrations: rule, value, verdict
  paper/tables/tab_c2c1_tests.tex    the 10 registration-1 confirmatory tests
"""
import collections, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DER, RES, PAPER = ROOT / "data" / "derived", ROOT / "results", ROOT / "paper"
HEADER = "% AUTO-GENERATED by scripts/paper_c2c1.py from results/ -- do not edit by hand.\n"
TEST_KEYS = ["estimate", "se", "df", "p", "q", "r", "ci90", "n_donors", "n_obs", "class", "n_saa_neg", "n_saa_pos"]


def export():
    m = json.load(open(DER / "models.json"))
    g = json.load(open(DER / "phenotypes" / "gates_prelink.json"))
    s = json.load(open(DER / "scrn" / "gate.json"))
    d0 = json.load(open(DER / "day0_gate_v2.json"))
    b0 = json.load(open(DER / "da_relabel" / "da_relabel.json"))
    gd = json.load(open(DER / "phenotypes_da" / "gates_da.json"))
    pick = lambda r: {k: r[k] for k in TEST_KEYS if k in r}
    sens = {}
    for v, fams in m["sensitivity"].items():
        if v == "S5_leave_one_out":
            sens[v] = {p: {k: x[k] for k in ("beta3_full", "loo_min", "loo_max", "n_sign_changes")} for p, x in fams.items()}
        else:
            sens[v] = dict(collections.Counter(r.get("class", "not_estimable") for f in fams.values() for r in f.values()))
    r1 = {
        "source": "data/derived (models.json v1.0.0, gates_prelink.json, scrn/gate.json, day0_gate_v2.json)",
        "reproduction": {"runs": s["runs"], "lines": s["distinct_lines"], "r_th": s["gate_primary"]["pearson_r"],
                         "n": s["gate_primary"]["n"], "r_th_2umi": s["gate_sensitivity_2umi"]["pearson_r"],
                         "verdict": s["gate_verdict"]},
        "A0_4": {k: d0["primary_published_outcome"][k] for k in ("n", "n_high", "n_low", "cv_auc_mean", "cv_auc_sd", "perm_p")}
                | {"batch_only_auc": d0["S3_batch_only"]["cv_auc_mean"], "genes_kept": d0["rows_kept_mean_ge_50"],
                   "verdict": d0["verdict"], "v010_auc": 0.573},
        "A0_2": {k: {"icc": v["icc"], "ci95": v["ci95"], "pass": v["pass"], "gating": v["gating"]} for k, v in g["A0_2"].items()},
        "A0_3": g["A0_3"], "sample": m["sample"], "A0_1": m["A0_1"], "A0_5": m["A0_5"],
        "tests": {fam: {p: pick(r) for p, r in m[fam].items()} for fam in ("H1", "H2", "H3_SAA", "H3_NSDISS")},
        "sensitivity_class_counts": sens,
    }
    pre = {
        "source": "data/derived (da_relabel.json v1.0.0, phenotypes_da/gates_da.json v1.0.0)",
        "calibration": {k: b0["calibration"][k] for k in ("t", "r_at_t", "r_old_rule", "n_donor_lines",
                                                          "median_new_da_frac", "median_old_da_frac")}
                       | {"grid_min": min(b0["calibration"]["grid"]), "grid_max": max(b0["calibration"]["grid"])},
        "markers": b0["markers"], "marker_log2_ratio_median": b0["pass2"]["marker_log2_ratio_median"],
        "marker_share_runs_gt0": b0["pass2"]["marker_share_runs_gt0"],
        "n_da_cells_median": b0["pass2"]["n_da_cells_median"], "runs_lt_100_da_cells": b0["pass2"]["runs_lt_100_da_cells"],
        "genes_kept_da": gd["info"]["n_genes_kept_da"], "geneset_sizes": gd["info"]["geneset_sizes_kept"],
        "G_cells": gd["info"]["G_cells"],
        "G_icc": {k: {kk: v[kk] for kk in ("icc", "ci95", "jerber_across_batch_icc", "jerber_ci95") if kk in v}
                  for k, v in gd["G_icc"].items()},
    }
    json.dump(r1, open(RES / "c2c1_registration1.json", "w"), indent=1)
    json.dump(pre, open(RES / "c2c2_prelink.json", "w"), indent=1)
    print("written results/c2c1_registration1.json, results/c2c2_prelink.json")


def f2(x):
    return f"{x:.2f}".replace("-", "$-$")


def fp(p):
    return f"{p:.3f}" if p < 0.1 else f"{p:.2f}"


def pct(x):
    return f"{100 * x:.0f}"


def numbers(r1, pre, c2):
    t = r1["tests"]
    cls = collections.Counter(r["class"] for f in t.values() for r in f.values() if r["class"] != "dropped_by_A0-5")
    sup_sens = sum(c.get("supported", 0) for k, c in r1["sensitivity_class_counts"].items() if k != "S5_leave_one_out")
    a2, gi, cal = r1["A0_2"], pre["G_icc"], pre["calibration"]
    h1 = t["H1"]["P2"]
    mac = {
        "cconeRuns": r1["reproduction"]["runs"], "cconeLines": r1["reproduction"]["lines"],
        "cconeReproR": f"{r1['reproduction']['r_th']:.3f}", "cconeReproN": r1["reproduction"]["n"],
        "cconeAucv": f"{r1['A0_4']['v010_auc']:.2f}", "cconeAuc": f2(r1["A0_4"]["cv_auc_mean"]),
        "cconeAucSD": f2(r1["A0_4"]["cv_auc_sd"]), "cconeAucP": fp(r1["A0_4"]["perm_p"]),
        "cconeAucBatch": f2(r1["A0_4"]["batch_only_auc"]), "cconeDayZeroGenes": f"{r1['A0_4']['genes_kept']:,}".replace(",", "{,}"),
        "cconeHigh": r1["A0_4"]["n_high"], "cconeLow": r1["A0_4"]["n_low"],
        "cconeIccPone": f2(a2["P1"]["icc"]), "cconeIccPtwo": f2(a2["P2"]["icc"]),
        "cconeIccPthree": f2(a2["P3"]["icc"]), "cconeIccPfour": f2(a2["P4"]["icc"]),
        "cconeAthreeExcl": r1["A0_3"]["n_donor_lines_excluded"], "cconeN": r1["sample"]["n_after_A0_3"],
        "cconeAzeroOne": r1["A0_1"]["n_meeting_rule"],
        "cconeAfivePthree": pct(r1["A0_5"]["P3"]["share_same_sign"]), "cconeAfivePthreeN": r1["A0_5"]["P3"]["n_genes"],
        "cconeAfivePfour": pct(r1["A0_5"]["P4"]["share_same_sign"]), "cconeAfivePfourN": r1["A0_5"]["P4"]["n_genes"],
        "cconeNtests": sum(cls.values()), "cconeNsup": cls.get("supported", 0), "cconeNeq": cls.get("equivalent", 0),
        "cconeNinc": cls.get("inconclusive", 0), "cconeSensSup": sup_sens,
        "cconeHoneBeta": f2(h1["estimate"]), "cconeHoneP": fp(h1["p"]), "cconeHoneR": f2(h1["r"]),
        "cconeHoneRlo": f2(h1["ci90"][0]), "cconeHoneRhi": f2(h1["ci90"][1]), "cconeVisits": h1["n_obs"],
        "cconeHthreeR": f2(t["H1"]["P3"]["r"]), "cconeHthreeP": fp(t["H1"]["P3"]["p"]),
        "cconeSBRn": t["H2"]["P2"]["n_donors"], "cconeSBRobs": t["H2"]["P2"]["n_obs"],
        "cconeSAAneg": t["H3_SAA"]["P2"]["n_saa_neg"], "cconeSAAn": t["H3_SAA"]["P2"]["n_donors"],
        "cconeNSDn": t["H3_NSDISS"]["P2"]["n_donors"],
        # registration II, pre-link (B0, G-cells, G-icc)
        "cctwoT": f2(cal["t"]), "cctwoGridMin": f2(cal["grid_min"]), "cctwoGridMax": f2(cal["grid_max"]),
        "cctwoCalR": f2(cal["r_at_t"]), "cctwoCalRold": f2(cal["r_old_rule"]),
        "cctwoDAfrac": pct(cal["median_new_da_frac"]), "cctwoDAfracOld": pct(cal["median_old_da_frac"]),
        "cctwoDAcells": f"{pre['n_da_cells_median']:,.0f}".replace(",", "{,}"), "cctwoDAlow": pre["runs_lt_100_da_cells"],
        "cctwoGenesDA": f"{pre['genes_kept_da']:,}".replace(",", "{,}"),
        "cctwoDthreeGenes": pre["geneset_sizes"]["D3"], "cctwoDfourGenes": pre["geneset_sizes"]["D4"],
        "cctwoGADone": f2(pre["marker_log2_ratio_median"]["GAD1"]), "cctwoSLCsix": f2(pre["marker_log2_ratio_median"]["SLC17A6"]),
        "cctwoSLCthree": f2(pre["marker_log2_ratio_median"]["SLC6A3"]), "cctwoTH": f2(pre["marker_log2_ratio_median"]["TH"]),
    }
    for k, name in (("D1", "Done"), ("D2", "Dtwo"), ("D3", "Dthree"), ("D4", "Dfour")):
        mac[f"cctwoIcc{name}"] = f2(gi[k]["icc"])
        mac[f"cctwoJer{name}"] = f2(gi[k]["jerber_across_batch_icc"])
    mac["cctwoJerDtwoLo"], mac["cctwoJerDtwoHi"] = (f2(x) for x in gi["D2"]["jerber_ci95"])
    return HEADER + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in mac.items())


def gates_table(r1, pre, c2):
    a2, gi, cal, g = r1["A0_2"], pre["G_icc"], pre["calibration"], c2["g"]["new"]
    ok = lambda b: "pass" if b else "fail"
    rows = [
        ("\\multicolumn{4}{l}{\\emph{Registration 1 (all-cell phenotypes)}}",),
        ("A0-6 Reproduction", "$r(\\%\\mathrm{TH}^+) \\ge 0.80$ vs.\\ published",
         f"$r = {r1['reproduction']['r_th']:.3f}$ ($n={r1['reproduction']['n']}$)", r1["reproduction"]["verdict"]),
        ("A0-4 Positive control", "day-0 CV AUC $\\ge 0.75$, $p<0.05$",
         f"AUC {r1['A0_4']['cv_auc_mean']:.2f}, $p={fp(r1['A0_4']['perm_p'])}$", r1["A0_4"]["verdict"]),
        ("A0-2 Stability", "$\\mathrm{ICC} \\ge 0.5$",
         ", ".join(f"{k} {f2(a2[k]['icc'])}" for k in ("P1", "P2", "P3", "P4")), "P1 fail; P2--P4 pass"),
        ("A0-3 Cells", "$\\ge 1{,}000$ QC cells per run", f"{r1['A0_3']['n_donor_lines_excluded']} line excluded", "pass"),
        ("A0-1 Linkage", "$\\ge 30$ donors with $\\ge 3$ OFF visits over $\\ge 2$\\,y",
         f"{r1['A0_1']['n_meeting_rule']}/{r1['A0_1']['n_pd_donors']}", ok(r1["A0_1"]["pass"])),
        ("A0-5 Coherence", "$\\ge 80\\%$ member genes share sign",
         f"P3 {pct(r1['A0_5']['P3']['share_same_sign'])}\\%, P4 {pct(r1['A0_5']['P4']['share_same_sign'])}\\%", "fail (both)"),
        ("\\multicolumn{4}{l}{\\emph{Registration II (DA-neuron phenotypes)}}",),
        ("G-cells", "$\\ge 100$ DA cells per run", f"{pre['G_cells']['donor_lines_excluded']} lines excluded", "pass"),
        ("G-icc", "FOUNDIN $\\ge 0.5$ and Jerber $\\ge 0.40$",
         ", ".join(f"{k} {f2(gi[k]['icc'])}/{f2(gi[k]['jerber_across_batch_icc'])}" for k in ("D1", "D2", "D3", "D4")),
         "D2, D4 pass"),
        ("G-eQTL", "concordance $\\ge 0.70$, $\\pi_1 \\ge 0.30$, both $>$ null P95",
         f"{f2(g['sign_concordance'])}, {f2(g['pi1'])} ($m={g['n_tested']}$)", "pass"),
        ("A0-1 Linkage", "as registration 1", f"{c2['m']['A0_1']['n_meeting_rule']}/{c2['m']['sample']['n_after_G_cells']}", "pass"),
        ("A0-5 Coherence (D4)", "$\\ge 80\\%$ member genes share sign",
         f"{pct(c2['m']['A0_5_D4']['share_same_sign'])}\\% of {c2['m']['A0_5_D4']['n_genes']}", "fail"),
    ]
    out = [HEADER, "\\begin{table*}[!t]\n\\centering\n\\caption{Gates of both registrations: rule fixed before the data were seen, observed value, verdict.}\n",
           "\\label{tab:gates}\n\\footnotesize\n\\begin{tabular}{p{2.9cm}p{5.4cm}p{5.6cm}p{2.4cm}}\n\\toprule\n",
           "Gate & Rule & Observed & Verdict \\\\\n\\midrule\n"]
    out += [(r[0] if len(r) == 1 else " & ".join(r)) + " \\\\\n" for r in rows]
    out.append("\\bottomrule\n\\end{tabular}\n\\end{table*}\n")
    return "".join(out)


def tests_table(r1):
    t = r1["tests"]
    lab = {"H1": "H1 UPDRS III slope", "H2": "H2 putamen SBR slope", "H3_SAA": "H3 SAA status", "H3_NSDISS": "H3 NSD-ISS stage"}
    out = [HEADER, "\\begin{table}[!t]\n\\centering\n\\caption{Registration 1: confirmatory tests of the all-cell phenotypes "
                   "(partial $r$ with 90\\% CI; $q$ = BH within family).}\n\\label{tab:c2c1_tests}\n\\scriptsize\n"
                   "\\setlength{\\tabcolsep}{3pt}\n\\begin{tabular}{llrrrrl}\n\\toprule\n"
                   "Family & $P$ & $n$ & $r$ & 90\\% CI & $q$ & Class \\\\\n\\midrule\n"]
    for fam, ph in t.items():
        for i, (p, r) in enumerate(ph.items()):
            c = r["class"].replace("dropped_by_A0-5", "not tested (A0-5)")
            q = fp(r["q"]) if "q" in r else "--"
            out.append(f"{lab[fam] if i == 0 else ''} & {p} & {r['n_donors']} & {f2(r['r'])} & "
                       f"[{f2(r['ci90'][0])}, {f2(r['ci90'][1])}] & {q} & {c} \\\\\n")
    out.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    return "".join(out)


def main():
    if sys.argv[1:] == ["export"]:
        return export()
    r1 = json.load(open(RES / "c2c1_registration1.json"))
    pre = json.load(open(RES / "c2c2_prelink.json"))
    c2 = {"m": json.load(open(RES / "c2c2_models_da.json")), "g": json.load(open(RES / "c2c2_g_eqtl.json"))}
    (PAPER / "generated" / "c2c1_numbers.tex").write_text(numbers(r1, pre, c2), encoding="utf-8")
    (PAPER / "tables" / "tab_gates.tex").write_text(gates_table(r1, pre, c2), encoding="utf-8")
    (PAPER / "tables" / "tab_c2c1_tests.tex").write_text(tests_table(r1), encoding="utf-8")
    print("written generated/c2c1_numbers.tex, tables/tab_gates.tex, tables/tab_c2c1_tests.tex")


if __name__ == "__main__":
    main()
